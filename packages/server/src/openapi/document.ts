import { OpenApiGeneratorV3 } from "@asteasolutions/zod-to-openapi";
import { OpenAPIHono } from "@hono/zod-openapi";
import { stringify } from "yaml";
import { globalRegistry, type ZodType } from "zod";
import { createApiRoutes } from "../routes/index.ts";
import * as schemas from "./schemas.ts";

const tags = [
  "Auth",
  "Bootstrap",
  "Users",
  "Models",
  "Providers",
  "Agents",
  "Environments",
  "Runs",
  "Sessions",
  "Files",
  "Tasks",
  "Issues",
  "Knowledge",
];

const isSchema = (value: unknown): value is ZodType =>
  typeof value === "object" && value !== null && "_zod" in value;

/** Orders named schemas so each comes after the named schemas it contains. */
function dependenciesFirst(roots: ZodType[]) {
  const ordered: ZodType[] = [];
  const seen = new Set<unknown>();
  const visit = (value: unknown, root: boolean) => {
    if (Array.isArray(value)) return value.forEach((item) => visit(item, false));
    if (!isSchema(value)) {
      if (value && typeof value === "object" && !root)
        for (const item of Object.values(value)) visit(item, false);
      return;
    }
    if (seen.has(value)) return;
    seen.add(value);
    const def = value._zod.def as unknown as Record<string, unknown>;
    for (const [key, child] of Object.entries(def)) if (key !== "checks") visit(child, false);
    if (globalRegistry.get(value)?.id) ordered.push(value);
  };
  for (const schema of roots) visit(schema, true);
  return ordered;
}

/** The HTTP contract, generated from the route definitions. */
export function createApiDocument() {
  const app = new OpenAPIHono();
  app.route("/api", createApiRoutes());
  const definitions: ConstructorParameters<typeof OpenApiGeneratorV3>[0] = [
    // Named schemas come first: a component first reached through `.nullable()`
    // would otherwise be generated as nullable everywhere. Routes that read their
    // own body also reference some of these only by name.
    ...dependenciesFirst(Object.values(schemas)).map((schema) => ({
      type: "schema" as const,
      schema,
    })),
    ...app.openAPIRegistry.definitions,
    {
      type: "component",
      componentType: "securitySchemes",
      name: "carmelSession",
      component: { type: "apiKey", in: "cookie", name: "carmel_session" },
    },
  ];
  return new OpenApiGeneratorV3(definitions).generateDocument({
    openapi: "3.0.3",
    info: {
      title: "Carmel Agent API",
      version: "1.0.0",
      description:
        "Authoritative HTTP contract for native and web Carmel Agent clients. Live run events and state notifications use the authenticated /api/updates WebSocket.",
    },
    servers: [{ url: "/" }],
    security: [{ carmelSession: [] }],
    tags: tags.map((name) => ({ name })),
  });
}

export function renderApiDocument() {
  return `# Generated by \`pnpm openapi\` from the server's route definitions. Do not edit.\n${stringify(createApiDocument(), { aliasDuplicateObjects: false, lineWidth: 0 })}`;
}
